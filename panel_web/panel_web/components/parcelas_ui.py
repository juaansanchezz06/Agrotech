def bloque_rango_sensor(
    titulo: str,
    val_min: str,
    campo_min: str,
    val_max: str,
    campo_max: str,
) -> rx.Component:
    return rx.vstack(
        rx.text(titulo, size="2", weight="medium", color="var(--gray-12)"),
        rx.hstack(
            rx.input(
                placeholder="Mín",
                value=val_min,
                on_change=lambda val: GestorParcelasState.set_campo(campo_min, val),
                size="2",
                variant="surface",
                width="100%",
            ),
            rx.input(
                placeholder="Máx",
                value=val_max,
                on_change=lambda val: GestorParcelasState.set_campo(campo_max, val),
                size="2",
                variant="surface",
                width="100%",
            ),
            spacing="2",
            width="100%",
        ),
        padding="0.75em",
        border_radius="10px",
        background_color="var(--gray-3)",
        border="1px solid var(--gray-4)",
        spacing="2",
        align="start",
        width="100%",
    )


def ilustracion_parcela(tipo: str) -> rx.Component:
    return rx.center(
        rx.match(
            tipo,
            ("invernadero", rx.html(SVG_INVERNADERO)),
            ("vinedo", rx.html(SVG_VINEDO)),
            ("huerto", rx.html(SVG_HUERTO)),
            ("surcos", rx.html(SVG_SURCOS)),
            rx.html(SVG_CAMPO),
        ),
        width="100%",
        height="104px",
        border_radius="12px",
        background_color="var(--gray-3)",
        border="1px solid var(--gray-4)",
        margin_y="0.35em",
    )


